                    <h4>Ethical Rule</h4>

                    <p>
                        Verumkaithari is strictly defensive. If an opponent is injured, the practitioner
                        is obligated to apply Marma healing treatments immediately.
                    </p>


                    <h3>7. Marma Chikilsathari (Vital Point Healing)</h3>

                    <p>
                        The backbone of Kalari system. It involves deep knowledge of the 107 Marma points
                        (intersections of nerves, veins, muscles, bones, and joints where Prana flows).
                        Treatment focuses primarily on balancing the Vatha humor to harmonize bodily energy
                        and heal trauma or chronic ailments where standard medicine struggles.
                    </p>


                    <h3>8. Upasanathari (Internal Consciousness &amp; Mastery)</h3>

                    <p>
                        The final meditative phase where practitioners sit on a traditional wooden platform
                        to internalize all learned combat tactics, align with nature, and develop spiritual clarity.
                    </p>

                    <p>
                        Upon completing this stage, the master reveals the secretive Pathinettadavukal
                        (18 vital tactics), graduating the practitioner into a full Kalari Master (Gurukkal)
                        qualified to pass down the lineage.
                    </p>

