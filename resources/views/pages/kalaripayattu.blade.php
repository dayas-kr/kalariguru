                        <li>Strengthens self-discipline</li>
                        <li>Improves stress resilience</li>
                        <li>Encourages deep self-awareness</li>
                    </ul>

                    <h3>Physical</h3>
                    <ul>
                        <li>Enhances flexibility</li>
                        <li>Improves physical strength</li>
                        <li>Develops reflex speed</li>
                        <li>Increases dynamic energy</li>
                        <li>Supports natural immunity</li>
                    </ul>


                    <h2>Ashtatharikal (The Eight Stages of Training)</h2>

                    <h3>1. Vanakkathari (Salutation Routines)</h3>

                    <p>
                        The foundational stage consists of four sequential salutations:
                        Yeka Dikku (one direction), Eratta Dikku (two directions), Chathur Dikku
                        (four directions), and Ashtta Dikku Vanakkam (eight directions).
                    </p>

                    <p>
                        Performed near the Poothara, these pre-arranged sequences pay respect to the
                        Easwara (Divine) and generations of Gurus while conditioning the inner body.
                        Students touch the feet of the master, the Poothara, and the Guruthara to seek blessings.
                    </p>

                    <p>
                        Kalari transcends caste, creed, religion, gender, and age, focusing solely on humanity.
                        Vanakkathari builds foundational strength, prevents practice injuries, and instills equality.
                    </p>


                    <h3>2. Chuvaduthari (Stances &amp; Steps)</h3>

                    <p>
                        Consisting of 18 foundational steps and Ashttavadivukal (eight animal postures),
                        this phase conditions body flexibility in preparation for armed and unarmed combat.
                    </p>

