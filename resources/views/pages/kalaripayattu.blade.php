                    <h3>3. Meythari (Physical Conditioning)</h3>

                    <p>
                        Focuses on body control, agility, mental endurance, and stamina. Techniques include
                        Kaaleduppu, Meypayattu, Chumattadi, Kaikuthi payattu, Vettuchuvadu, Kalamchavittu,
                        and Chaattapayattu.
                    </p>

                    <p>
                        It balances physical speed with mental reflexes—crucial for weapon mastery and
                        long-term health.
                    </p>


                    <h3>4. Kolthari (Wooden Weapons)</h3>

                    <p>
                        Training using wooden implements to build reflexes and hand-eye coordination.
                        Includes Kettukari (long stick), Muchaan (short stick), Otah (curved stick),
                        Pondhi, Chottichaan, Erattavadi, and Perundhallu.
                    </p>

                    <p>
                        Combinations are typically structured in sets of 6, 12, or 18.
                    </p>


                    <h3>5. Angathari (Metal Weapons)</h3>

                    <p>
                        Advanced combat training that maximizes physical power, courage, and tactical focus.
                        Techniques utilize sharp metal weapons, including:
