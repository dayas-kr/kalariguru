                    <h2>Overview &amp; Lineage</h2>

                    <p>
                        The practice of Kalaripayattu, along with its invaluable lifestyle, is uniquely designed
                        to enhance human potential and maintain the equilibrium of a person's physical, mental,
                        and spiritual layers of life.
                    </p>

                    <p>
                        As one of the most ancient martial arts, Kalaripayattu originated in the Gurukulam
                        tradition of ancient tribal (Gothra) culture in India. Historically, it evolved through
                        three main stylistic variations:
                    </p>

                    <h3>Arappukai Version</h3>
                    <p>
                        Focused on high jumps, leg extensions, bending and locking the body in low-middle
                        stances, complex stepping exercises, flexibility training, and weapon applications.
                        It emphasizes tricky up-and-down movements and dynamic jumping tactics.
                    </p>

                    <h3>Vatten Thirippu Version</h3>
                    <p>
                        Characterized by diverse somersaults (Malakkareethikal), extensive foot and hand
                        patterns (Kalam chavuttu reethikal and Vettu chuvadukal), and specialized body
                        conditioning.
                    </p>

                    <h3>Pillathangi Version</h3>
                    <p>
                        Focuses on ground-level stretching combinations, rapid forward and backward
                        movements, and developing hand speed and strength. It incorporates floor-striking
                        combinations and low-stance hand techniques (Kaikuthi payattu).
                    </p>

                    <p>
                        Over time, regional variants took names from specific Kalari Gurukals (masters),
                        family lineages, or villages (e.g., Kadathanadu, Thulunadu, Odimurisheri).
                        After 1957, Kalaripayattu associations formed a unified body and standardized the
                        styles by region: Northern (Vadakkan), Southern (Thekkan), and Central (Madhya)
                        Kerala, introducing formal Kalari competitions.
                    </p>


                    <h2>Key Benefits</h2>

